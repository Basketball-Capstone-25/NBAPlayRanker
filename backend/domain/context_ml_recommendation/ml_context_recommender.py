def _parse_margin_hint(value: Any) -> Optional[float]:
    if value is None:
        return None
    text = str(value).strip().lower()
    if not text:
        return None

    if _MARGIN_TIED_RE.search(text):
        return 0.0

    m = _MARGIN_DOWN_RE.search(text)
    if m:
        n = _num_from_token(m.group("n"))
        if n is not None:
            return float(-abs(n))

    m = _MARGIN_UP_RE.search(text)
    if m:
        n = _num_from_token(m.group("n"))
        if n is not None:
            return float(abs(n))

    return None


def _parse_period_hint(value: Any) -> Optional[int]:
    if value is None:
        return None

    numeric = _safe_float(value)
    if numeric is not None:
        period = int(round(float(numeric)))
        if 1 <= period <= 5:
            return period

    text = str(value).strip().lower()
    if not text:
        return None

    for parsed_period, pattern in _PERIOD_PATTERNS:
        if pattern.search(text):
            return parsed_period

    return None


def _parse_time_hint(value: Any) -> Optional[float]:
    if value is None:
        return None

    numeric = _safe_float(value)
    if numeric is not None and 0.0 <= float(numeric) <= 720.0:
        return float(numeric)

    text = str(value).strip().lower()
    if not text:
        return None

    m = _TIME_MMSS_RE.search(text)
    if m:
        mm = int(m.group("mm"))
        ss = int(m.group("ss"))
        if 0 <= ss < 60:
            return float(mm * 60 + ss)

    m = _TIME_SECONDS_RE.search(text)
    if m:
        return float(int(m.group("s")))

    m = _TIME_MINUTES_RE.search(text)
    if m:
        return float(int(m.group("m")) * 60)

    return None


def validate_context_guardrails() -> Dict[str, Any]:
    """
    Small programmatic validation helper for core context mappings.
    This does not replace a real test suite, but it gives the project a
    deterministic self-check for the most important parsing guardrails.
    """
    checks = [
        ("margin_down_5", _parse_margin_hint("down 5"), -5.0),
        ("margin_leading_3", _parse_margin_hint("leading by 3"), 3.0),
        ("margin_tied", _parse_margin_hint("tie game"), 0.0),
        ("period_q4", _parse_period_hint("Q4"), 4),
        ("period_ot", _parse_period_hint("overtime"), 5),
        ("clock_mmss", _parse_time_hint("0:28"), 28.0),
        ("clock_seconds", _parse_time_hint("28 seconds"), 28.0),
        ("clock_minutes", _parse_time_hint("2 minutes"), 120.0),
    ]

    details: List[Dict[str, Any]] = []
    passed = 0

    for name, actual, expected in checks:
        ok = actual == expected
        if ok:
            passed += 1
        details.append(
            {
                "name": name,
                "actual": actual,
                "expected": expected,
                "ok": ok,
            }
        )

    return {
        "status": "ok" if passed == len(checks) else "failed",
        "passed": passed,
        "total": len(checks),
        "details": details,
        "module_version": MODULE_VERSION,
    }


