from __future__ import annotations

"""
backend/ml_context_recommender.py

Purpose (defense-friendly):
- Centralize the full "Context + ML" ranking logic in one reusable module.
- Let advanced NLP context change the RANKING itself, not just the explanation text.
- Keep the logic transparent enough to defend to instructors / committee.
- Add strict guardrails so missing/ambiguous NLP outputs do NOT send garbage data
  into the ranking logic.

Important design choices:
1) This module does NOT import spaCy or NLTK directly.
   It only consumes already-parsed context, which keeps memory overhead low in
   the ranking path and avoids extra model loads during requests.
2) If parsing fails or is incomplete, this module falls back to safe neutral
   defaults:
      - margin = 0.0
      - period = 4
      - time_remaining = 360.0
   Those defaults intentionally avoid extreme late-game bias.
3) RATIONALE is generated by a deterministic template only.
   No language model is used here, so there is no hallucination risk in the
   coaching explanation text produced by this module.
4) A small built-in validation helper is included so the project can
   programmatically verify core mappings like:
      - "down 5" -> -5
      - "leading by 3" -> 3
      - "Q4" -> 4
      - "0:28" -> 28
"""

