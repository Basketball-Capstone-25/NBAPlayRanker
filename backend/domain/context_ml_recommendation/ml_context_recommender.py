_MARGIN_DOWN_RE = re.compile(
    r"\b(?:down|trailing|behind)\s*(?:by\s*)?(?P<n>\d{1,2}|one|two|three|four|five|six|seven|eight|nine|ten)\b",
    flags=re.IGNORECASE,
)
_MARGIN_UP_RE = re.compile(
    r"\b(?:up|leading|ahead)\s*(?:by\s*)?(?P<n>\d{1,2}|one|two|three|four|five|six|seven|eight|nine|ten)\b",
    flags=re.IGNORECASE,
)
_MARGIN_TIED_RE = re.compile(r"\b(?:tie|tied|even)\b", flags=re.IGNORECASE)

_PERIOD_PATTERNS: Tuple[Tuple[int, re.Pattern[str]], ...] = (
    (5, re.compile(r"\b(?:ot|overtime)\b", flags=re.IGNORECASE)),
    (4, re.compile(r"\b(?:q\s*4|4th\s*(?:q|quarter)|fourth\s+quarter)\b", flags=re.IGNORECASE)),
    (3, re.compile(r"\b(?:q\s*3|3rd\s*(?:q|quarter)|third\s+quarter)\b", flags=re.IGNORECASE)),
    (2, re.compile(r"\b(?:q\s*2|2nd\s*(?:q|quarter)|second\s+quarter)\b", flags=re.IGNORECASE)),
    (1, re.compile(r"\b(?:q\s*1|1st\s*(?:q|quarter)|first\s+quarter)\b", flags=re.IGNORECASE)),
)

_TIME_MMSS_RE = re.compile(r"\b(?P<mm>\d{1,2})\s*:\s*(?P<ss>\d{2})\b")
_TIME_SECONDS_RE = re.compile(r"\b(?P<s>\d{1,3})\s*(?:s|sec|secs|second|seconds)\b", flags=re.IGNORECASE)
_TIME_MINUTES_RE = re.compile(r"\b(?P<m>\d{1,2})\s*(?:m|min|mins|minute|minutes)\b", flags=re.IGNORECASE)


