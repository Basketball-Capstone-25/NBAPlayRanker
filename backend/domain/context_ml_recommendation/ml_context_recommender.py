def _sanitize_numeric_context(
    raw_margin: Any,
    raw_period: Any,
    raw_time_remaining: Any,
) -> Tuple[float, int, float, List[str], List[str]]:
    """
    Returns:
      margin, period, time_remaining, defaults_used, guardrails
    """
    defaults_used: List[str] = []
    guardrails: List[str] = []

    # -------------------------
    # margin
    # -------------------------
    margin = _safe_float(raw_margin)
    if margin is None:
        margin = _parse_margin_hint(raw_margin)

    if margin is None:
        margin = DEFAULT_MARGIN
        defaults_used.append("margin")
        guardrails.append("margin defaulted to 0.0 because no reliable score margin was parsed.")
    else:
        if float(margin) < -50.0 or float(margin) > 50.0:
            guardrails.append(f"margin {margin} was out of range and clamped into [-50, 50].")
        margin = float(_clamp(float(margin), -50.0, 50.0))

    # -------------------------
    # period
    # -------------------------
    period = _parse_period_hint(raw_period)
    if period is None:
        period = DEFAULT_PERIOD
        defaults_used.append("period")
        guardrails.append("period defaulted to 4 because no reliable quarter/period was parsed.")

    # -------------------------
    # time remaining
    # -------------------------
    time_remaining = _parse_time_hint(raw_time_remaining)
    if time_remaining is None:
        time_remaining = DEFAULT_TIME_REMAINING
        defaults_used.append("time_remaining")
        guardrails.append("time_remaining defaulted to 360.0 seconds because no reliable clock value was parsed.")
    else:
        if float(time_remaining) < 0.0 or float(time_remaining) > 720.0:
            guardrails.append(f"time_remaining {time_remaining} was out of range and clamped into [0, 720].")
        time_remaining = float(_clamp(float(time_remaining), 0.0, 720.0))

    return float(margin), int(period), float(time_remaining), defaults_used, guardrails


def _normalize_context(
    margin: Any,
    period: Any,
    time_remaining_period_sec: Any,
    context: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Central guardrail boundary for all recommender ranking inputs.

    If the parser gives clean values, they are preserved.
    If the parser gives nothing / invalid values, the recommender falls back to:
      margin=0.0, period=4, time_remaining=360.0
    and records exactly what happened in guardrail metadata.
    """
    raw = context.copy() if isinstance(context, dict) else {}

    # Prefer explicit parser/context values, then function args.
    raw_margin = raw.get("margin", margin)
    raw_period = raw.get("period", period)
    raw_time_remaining = raw.get("time_remaining", time_remaining_period_sec)

    safe_margin, safe_period, safe_time_remaining, defaults_used, guardrails = _sanitize_numeric_context(
        raw_margin=raw_margin,
        raw_period=raw_period,
        raw_time_remaining=raw_time_remaining,
    )

    out: Dict[str, Any] = {
        "margin": safe_margin,
        "period": safe_period,
        "time_remaining": safe_time_remaining,
        "shot_clock": None,
        "need": _safe_str(raw.get("need")),
        "needs": _as_list_str(raw.get("needs")),
        "defense_style": _safe_str(raw.get("defense_style")),
        "pace": _safe_str(raw.get("pace")),
        "preferred_play_families": _as_list_str(raw.get("preferred_play_families")),
        "special_situations": _as_list_str(raw.get("special_situations")),
        "_defaults_used": defaults_used,
        "_guardrails": guardrails,
        "_parse_status": "defaulted" if defaults_used else "parsed",
        "_validation_ok": len(defaults_used) == 0,
    }

    shot_clock = _safe_float(raw.get("shot_clock"))
    if shot_clock is not None:
        out["shot_clock"] = _clamp(float(shot_clock), 0.0, 24.0)

    bool_keys = [
        "after_timeout",
        "slob",
        "blob",
        "advance_ball",
        "late_clock",
        "need3",
        "protect_lead",
        "end_of_quarter",
        "vs_switching",
        "must_stop",
        "quick2",
        "two_for_one",
        "hold_for_last",
        "foul_game",
        "no_three",
        "must_score",
        "safe",
    ]
    for key in bool_keys:
        out[key] = _truthy(raw.get(key))

    if out["need"] and out["need"] not in out["needs"]:
        out["needs"].append(out["need"])

    if out["after_timeout"] and "after_timeout" not in out["special_situations"]:
        out["special_situations"].append("after_timeout")
    if out["slob"] and "slob" not in out["special_situations"]:
        out["special_situations"].append("slob")
    if out["blob"] and "blob" not in out["special_situations"]:
        out["special_situations"].append("blob")
    if out["advance_ball"] and "advance_ball" not in out["special_situations"]:
        out["special_situations"].append("advance_ball")

    if out["need3"] and "need3" not in out["needs"]:
        out["needs"].append("need3")
    if out["quick2"] and "quick2" not in out["needs"]:
        out["needs"].append("quick2")
    if out["two_for_one"] and "two_for_one" not in out["needs"]:
        out["needs"].append("two_for_one")
    if out["hold_for_last"] and "last_shot" not in out["needs"]:
        out["needs"].append("last_shot")
    if out["must_score"] and "must_score" not in out["needs"]:
        out["needs"].append("must_score")
    if out["safe"] and "safe" not in out["needs"]:
        out["needs"].append("safe")

    if out["defense_style"] == "switch":
        out["vs_switching"] = True

    out["needs"] = _dedupe_keep_order(out["needs"])
    out["special_situations"] = _dedupe_keep_order(out["special_situations"])
    out["preferred_play_families"] = _dedupe_keep_order(out["preferred_play_families"])

    if _safe_str(raw.get("parser_version")):
        out["parser_version"] = str(raw["parser_version"]).strip()
    if _safe_str(raw.get("nlp_pipeline_version")):
        out["nlp_pipeline_version"] = str(raw["nlp_pipeline_version"]).strip()

    return out


def sanitize_context_for_ranking(
    context: Optional[Dict[str, Any]] = None,
    *,
    margin: Any = None,
    period: Any = None,
    time_remaining: Any = None,
) -> Dict[str, Any]:
    """
    Public helper so endpoint code can sanitize/normalize NLP context before
    it reaches ranking logic.

    This is the explicit integration boundary for:
    - fallback defaults
    - clamping
    - bool/special-situation normalization
    - audit metadata about what had to be defaulted
    """
    return _normalize_context(
        margin=margin,
        period=period,
        time_remaining_period_sec=time_remaining,
        context=context,
    )


def _context_priority_multiplier(
    ctx: Dict[str, Any],
    late_game_factor: float,
    trailing_factor: float,
    leading_factor: float,
) -> float:
    mult = 1.0
    if ctx["need"] in {"need3", "quick2", "two_for_one", "must_score"}:
        mult += 0.25 * late_game_factor
        mult += 0.20 * trailing_factor
    if ctx["need"] in {"safe"} or ctx["protect_lead"]:
        mult += 0.18 * leading_factor
    if ctx["after_timeout"] or ctx["slob"] or ctx["blob"]:
        mult += 0.08
    return float(mult)


def _make_context_label(
    ctx: Dict[str, Any],
    late_game_factor: float,
    trailing_factor: float,
    leading_factor: float,
) -> str:
    parts: List[str] = [label_context(late_game_factor, trailing_factor, leading_factor)]

    if ctx.get("need"):
        parts.append(str(ctx["need"]))
    if ctx.get("defense_style"):
        parts.append(str(ctx["defense_style"]))
    if ctx.get("after_timeout"):
        parts.append("ATO")
    elif ctx.get("slob"):
        parts.append("SLOB")
    elif ctx.get("blob"):
        parts.append("BLOB")

    if ctx.get("_defaults_used"):
        parts.append("guardrail-defaulted")

    return " | ".join(parts)


