def build_ml_matchup_table(
    season: str,
    our_team: str,
    opp_team: str,
    w_off: float = 0.7,
    w_def: float = 0.3,
    context: Optional[Dict[str, Any]] = None,
) -> pd.DataFrame:
    """
    Build the matchup table that contains BOTH:
      - Baseline prediction (PPP_BASELINE)
      - ML blend prediction (PPP_ML_BLEND)

    Advanced NLP context now influences the offense/defense blend weights.
    """
    team_df = _rec.team_df.copy()
    league_df = _rec.league_df.copy()
    ml_df = _get_ml_pred_df()

    if "PPP_ML" not in ml_df.columns:
        raise ValueError("ml_offense_ppp_predictions.csv must contain a PPP_ML column.")

    team_df = team_df.merge(
        ml_df,
        on=["SEASON", "TEAM_ABBREVIATION", "PLAY_TYPE"],
        how="left",
    )

    off = team_df.query(
        "SEASON == @season and TEAM_ABBREVIATION == @our_team and SIDE == 'offense'"
    ).copy()

    deff = team_df.query(
        "SEASON == @season and TEAM_ABBREVIATION == @opp_team and SIDE == 'defense'"
    ).copy()

    if off.empty:
        raise ValueError(f"No offensive data for {our_team} in season {season}")
    if deff.empty:
        raise ValueError(f"No defensive data for {opp_team} in season {season}")

    league_off = league_df.query(
        "SEASON == @season and SIDE == 'offense'"
    )[["PLAY_TYPE", "PPP"]].rename(columns={"PPP": "PPP_LEAGUE_OFF"})

    league_def = league_df.query(
        "SEASON == @season and SIDE == 'defense'"
    )[["PLAY_TYPE", "PPP"]].rename(columns={"PPP": "PPP_LEAGUE_DEF"})

    if league_off.empty or league_def.empty:
        raise ValueError(f"Missing league-average offense/defense data for season {season}")

    deff_subset = deff[
        [
            "PLAY_TYPE",
            "PPP",
            "POSS",
            "POSS_PCT",
            "RELIABILITY_WEIGHT",
            "EFG_PCT",
            "TOV_POSS_PCT",
        ]
    ].copy()

    merged = off.merge(
        deff_subset,
        on="PLAY_TYPE",
        suffixes=("_OFF", "_DEF"),
    )

    merged = merged.merge(league_off, on="PLAY_TYPE", how="left")
    merged = merged.merge(league_def, on="PLAY_TYPE", how="left")

    rel_off = merged["RELIABILITY_WEIGHT_OFF"].fillna(0.0)
    rel_def = merged["RELIABILITY_WEIGHT_DEF"].fillna(0.0)

    merged["PPP_OFF_SHRUNK"] = rel_off * merged["PPP_OFF"] + (1 - rel_off) * merged["PPP_LEAGUE_OFF"]
    merged["PPP_DEF_SHRUNK"] = rel_def * merged["PPP_DEF"] + (1 - rel_def) * merged["PPP_LEAGUE_DEF"]

    eff_w_off, eff_w_def = _resolve_effective_weights(context=context, w_off=w_off, w_def=w_def)

    merged["EFFECTIVE_W_OFF"] = float(eff_w_off)
    merged["EFFECTIVE_W_DEF"] = float(eff_w_def)

    merged["PPP_BASELINE"] = (
        float(eff_w_off) * merged["PPP_OFF_SHRUNK"]
        + float(eff_w_def) * (2 * merged["PPP_LEAGUE_OFF"] - merged["PPP_DEF_SHRUNK"])
    )

    merged = merged[merged["PPP_ML"].notna()].copy()
    if merged.empty:
        raise ValueError("No ML predictions available for this matchup (PPP_ML is missing).")

    merged["PPP_ML_BLEND"] = (
        float(eff_w_off) * merged["PPP_ML"]
        + float(eff_w_def) * (2 * merged["PPP_LEAGUE_OFF"] - merged["PPP_DEF_SHRUNK"])
    )

    merged["PLAY_FAMILY"] = merged["PLAY_TYPE"].apply(_play_family)
    return merged.reset_index(drop=True)


def apply_context_adjustments(
    df: pd.DataFrame,
    margin: Any,
    period: Any,
    time_remaining_period_sec: Any,
    context: Optional[Dict[str, Any]] = None,
) -> pd.DataFrame:
    """
    Apply both:
    - the legacy score/time adjustments already used in your app
    - NEW advanced NLP-aware adjustments that can materially change rank order

    Adds:
      QUICK_PRIORITY, BONUS_QUICK, BONUS_SCORE, PENALTY_PROTECT
      NEED_ADJ, DEFENSE_STYLE_ADJ, PACE_ADJ, SPECIAL_ADJ,
      FAMILY_PREF_ADJ, LATE_CLOCK_ADJ, BALL_SECURITY_PENALTY,
      LEGACY_CONTEXT_ADJ, NLP_CONTEXT_ADJ,
      CONTEXT_ADJ, PPP_CONTEXT, DELTA_VS_BASELINE,
      LATE_GAME_FACTOR, TRAILING_FACTOR, LEADING_FACTOR,
      CONTEXT_LABEL, RATIONALE

    Guardrail fields added:
      CONTEXT_DEFAULTS_USED, CONTEXT_GUARDRAILS, CONTEXT_PARSE_STATUS,
      CONTEXT_VALIDATION_OK, RATIONALE_MODE
    """
    out = df.copy()

    ctx = _normalize_context(
        margin=margin,
        period=period,
        time_remaining_period_sec=time_remaining_period_sec,
        context=context,
    )

    margin = float(ctx["margin"])
    period = int(ctx["period"])
    time_remaining_period_sec = float(ctx["time_remaining"])

    late_game_factor, trailing_factor, leading_factor = compute_context_factors(
        margin=margin,
        period=period,
        time_remaining_period_sec=time_remaining_period_sec,
    )

    urgency_mult = _context_priority_multiplier(ctx, late_game_factor, trailing_factor, leading_factor)

    out["PLAY_FAMILY"] = out["PLAY_TYPE"].apply(_play_family)

    # Make sure downstream columns exist even if source data is imperfect.
    if "EFG_PCT_OFF" not in out.columns:
        out["EFG_PCT_OFF"] = 0.0
    if "TOV_POSS_PCT_OFF" not in out.columns:
        out["TOV_POSS_PCT_OFF"] = 0.0

    out["EFG_PCT_OFF"] = pd.to_numeric(out["EFG_PCT_OFF"], errors="coerce").fillna(0.0)
    out["TOV_POSS_PCT_OFF"] = pd.to_numeric(out["TOV_POSS_PCT_OFF"], errors="coerce").fillna(0.0)

    # -----------------------------------------------------------------
    # Legacy adjustments (preserved for compatibility)
    # -----------------------------------------------------------------
    out["QUICK_PRIORITY"] = out["PLAY_TYPE"].map(QUICK_WEIGHTS).fillna(
        out["PLAY_FAMILY"].map(FAMILY_QUICK_WEIGHTS).fillna(0.0)
    )

    avg_efg = float(out["EFG_PCT_OFF"].mean()) if "EFG_PCT_OFF" in out.columns else 0.0
    avg_tov = float(out["TOV_POSS_PCT_OFF"].mean()) if "TOV_POSS_PCT_OFF" in out.columns else 0.0

    out["BONUS_QUICK"] = (
        0.04 * late_game_factor * (0.3 + trailing_factor) * out["QUICK_PRIORITY"]
    )

    out["BONUS_SCORE"] = (
        0.25
        * late_game_factor
        * trailing_factor
        * np.maximum(0.0, out["EFG_PCT_OFF"] - avg_efg)
    )

    out["PENALTY_PROTECT"] = (
        0.30
        * late_game_factor
        * leading_factor
        * np.maximum(0.0, out["TOV_POSS_PCT_OFF"] - avg_tov)
    )

    out["LEGACY_CONTEXT_ADJ"] = out["BONUS_QUICK"] + out["BONUS_SCORE"] - out["PENALTY_PROTECT"]

    # -----------------------------------------------------------------
    # Advanced NLP-aware adjustments
    # -----------------------------------------------------------------
    primary_need = ctx.get("need")
    defense_style = ctx.get("defense_style")
    pace = ctx.get("pace")
    preferred_families = set(ctx.get("preferred_play_families") or [])
    special_situations = list(ctx.get("special_situations") or [])

    def need_adj(family: str) -> float:
        base = _lookup_nested(NEED_FAMILY_BONUS, primary_need, family)
        if base == 0.0:
            return 0.0
        return float(base * urgency_mult)

    def defense_adj(family: str) -> float:
        base = _lookup_nested(DEFENSE_STYLE_FAMILY_BONUS, defense_style, family)
        if base == 0.0:
            return 0.0
        style_mult = 0.70 + 0.30 * late_game_factor
        if ctx.get("vs_switching") and family in {"cut", "post_up"}:
            style_mult += 0.10
        return float(base * style_mult)

    def pace_adj(family: str) -> float:
        base = _lookup_nested(PACE_FAMILY_BONUS, pace, family)
        if base == 0.0:
            return 0.0
        return float(base * (0.70 + 0.30 * late_game_factor))

    def special_adj(family: str) -> float:
        bonus = 0.0
        for special in special_situations:
            bonus += _lookup_nested(SPECIAL_FAMILY_BONUS, special, family)
        return float(bonus)

    def family_pref_adj(family: str) -> float:
        return _preferred_family_bonus(list(preferred_families), family)

    def late_clock_adj(family: str) -> float:
        shot_clock = _safe_float(ctx.get("shot_clock"))
        late_clock_flag = bool(ctx.get("late_clock"))
        short_clock = bool(shot_clock is not None and shot_clock <= 8)
        if not late_clock_flag and not short_clock:
            return 0.0

        base = _lookup_family_bonus(LATE_CLOCK_FAMILY_BONUS, family)
        if base == 0.0:
            return 0.0

        strength = 1.0
        if shot_clock is not None:
            strength = _clamp((8.0 - shot_clock) / 8.0 + 0.40, 0.40, 1.20)
        return float(base * strength)

    def ball_security_penalty(row: pd.Series) -> float:
        tov = float(row.get("TOV_POSS_PCT_OFF", avg_tov))
        family = str(row.get("PLAY_FAMILY", "other"))

        protect_state = bool(ctx.get("protect_lead") or ctx.get("safe"))
        if not protect_state and primary_need not in {"safe"}:
            return 0.0

        penalty = max(0.0, tov - avg_tov)
        penalty *= 0.35 * (0.60 + 0.40 * leading_factor)

        if family in RISKY_FAMILIES:
            penalty += 0.012
        if family in SECURE_FAMILIES:
            penalty -= 0.006

        return float(max(0.0, penalty))

    out["NEED_ADJ"] = out["PLAY_FAMILY"].apply(need_adj)
    out["DEFENSE_STYLE_ADJ"] = out["PLAY_FAMILY"].apply(defense_adj)
    out["PACE_ADJ"] = out["PLAY_FAMILY"].apply(pace_adj)
    out["SPECIAL_ADJ"] = out["PLAY_FAMILY"].apply(special_adj)
    out["FAMILY_PREF_ADJ"] = out["PLAY_FAMILY"].apply(family_pref_adj)
    out["LATE_CLOCK_ADJ"] = out["PLAY_FAMILY"].apply(late_clock_adj)
    out["BALL_SECURITY_PENALTY"] = out.apply(ball_security_penalty, axis=1)

    # Additional small structural nudges for mixed situations
    out["STRUCTURE_NUDGE"] = 0.0

    if defense_style == "switch":
        out.loc[out["PLAY_FAMILY"] == "post_up", "STRUCTURE_NUDGE"] += 0.010
        out.loc[out["PLAY_FAMILY"] == "cut", "STRUCTURE_NUDGE"] += 0.008

    if defense_style in {"zone_2_3", "zone_3_2", "zone_1_3_1", "generic_zone", "matchup_zone", "box_and_1"}:
        out.loc[out["PLAY_FAMILY"] == "off_screen", "STRUCTURE_NUDGE"] += 0.010
        out.loc[out["PLAY_FAMILY"] == "spot_up", "STRUCTURE_NUDGE"] += 0.008

    if primary_need == "need3":
        out.loc[out["PLAY_FAMILY"] == "post_up", "STRUCTURE_NUDGE"] -= 0.008

    if primary_need == "quick2":
        out.loc[out["PLAY_FAMILY"] == "transition", "STRUCTURE_NUDGE"] += 0.006
        out.loc[out["PLAY_FAMILY"] == "isolation", "STRUCTURE_NUDGE"] -= 0.006

    out["NLP_CONTEXT_ADJ"] = (
        out["NEED_ADJ"]
        + out["DEFENSE_STYLE_ADJ"]
        + out["PACE_ADJ"]
        + out["SPECIAL_ADJ"]
        + out["FAMILY_PREF_ADJ"]
        + out["LATE_CLOCK_ADJ"]
        + out["STRUCTURE_NUDGE"]
        - out["BALL_SECURITY_PENALTY"]
    )

    # -----------------------------------------------------------------
    # Final combination
    # -----------------------------------------------------------------
    out["CONTEXT_ADJ"] = out["LEGACY_CONTEXT_ADJ"] + out["NLP_CONTEXT_ADJ"]
    out["PPP_CONTEXT"] = out["PPP_ML_BLEND"] + out["CONTEXT_ADJ"]
    out["DELTA_VS_BASELINE"] = out["PPP_CONTEXT"] - out["PPP_BASELINE"]

    ctx_label = _make_context_label(ctx, late_game_factor, trailing_factor, leading_factor)
    out["CONTEXT_LABEL"] = ctx_label

    out["LATE_GAME_FACTOR"] = float(late_game_factor)
    out["TRAILING_FACTOR"] = float(trailing_factor)
    out["LEADING_FACTOR"] = float(leading_factor)

    out["CONTEXT_DEFAULTS_USED"] = ", ".join(ctx.get("_defaults_used", [])) if ctx.get("_defaults_used") else ""
    out["CONTEXT_GUARDRAILS"] = " | ".join(ctx.get("_guardrails", [])) if ctx.get("_guardrails") else ""
    out["CONTEXT_PARSE_STATUS"] = str(ctx.get("_parse_status", "parsed"))
    out["CONTEXT_VALIDATION_OK"] = bool(ctx.get("_validation_ok", True))
    out["RATIONALE_MODE"] = RATIONALE_MODE

    def rationale(row: pd.Series) -> str:
        parts: List[str] = []

        if float(row["NEED_ADJ"]) != 0.0 and primary_need:
            parts.append(f"need={primary_need}:{row['NEED_ADJ']:+.3f}")
        if float(row["DEFENSE_STYLE_ADJ"]) != 0.0 and defense_style:
            parts.append(f"defense={defense_style}:{row['DEFENSE_STYLE_ADJ']:+.3f}")
        if float(row["PACE_ADJ"]) != 0.0 and pace:
            parts.append(f"pace={pace}:{row['PACE_ADJ']:+.3f}")
        if float(row["SPECIAL_ADJ"]) != 0.0 and special_situations:
            parts.append(f"special:{row['SPECIAL_ADJ']:+.3f}")
        if float(row["FAMILY_PREF_ADJ"]) != 0.0:
            parts.append(f"family_match:{row['FAMILY_PREF_ADJ']:+.3f}")
        if float(row["LATE_CLOCK_ADJ"]) != 0.0:
            parts.append(f"late_clock:{row['LATE_CLOCK_ADJ']:+.3f}")
        if float(row["BALL_SECURITY_PENALTY"]) != 0.0:
            parts.append(f"ball_security:{-float(row['BALL_SECURITY_PENALTY']):+.3f}")

        detail = "; ".join(parts) if parts else "no extra NLP family adjustments"

        guardrail_note = ""
        if row["CONTEXT_PARSE_STATUS"] == "defaulted":
            guardrail_note = (
                f" Guardrail defaults used ({row['CONTEXT_DEFAULTS_USED'] or 'unspecified fields'}), "
                "so this ranking was kept in a neutral context rather than a forced late-game assumption."
            )

        return (
            f"{row['PLAY_TYPE']} [{row['PLAY_FAMILY']}]: "
            f"ML base {row['PPP_ML_BLEND']:.3f}, "
            f"legacy {row['LEGACY_CONTEXT_ADJ']:+.3f}, "
            f"NLP {row['NLP_CONTEXT_ADJ']:+.3f}, "
            f"total {row['CONTEXT_ADJ']:+.3f} ({ctx_label}). "
            f"Blend off/def={row['EFFECTIVE_W_OFF']:.2f}/{row['EFFECTIVE_W_DEF']:.2f}. "
            f"{detail}. "
            f"Late={late_game_factor:.2f}, trailing={trailing_factor:.2f}, leading={leading_factor:.2f}."
            f"{guardrail_note}"
        )

    out["RATIONALE"] = out.apply(rationale, axis=1)
    return out


def rank_ml_with_context(
    season: str,
    our_team: str,
    opp_team: str,
    margin: Any,
    period: Any,
    time_remaining_period_sec: Any,
    k: int = 5,
    w_off: float = 0.7,
    w_def: float = 0.3,
    context: Optional[Dict[str, Any]] = None,
) -> pd.DataFrame:
    """
    Full AI use case ranking:
      1) Build matchup with ML blend + baseline
      2) Let advanced NLP context alter blend weights
      3) Apply legacy + NLP-aware context adjustments
      4) Rank by PPP_CONTEXT

    Safe fallback behavior for malformed / underspecified prompts:
      - margin -> 0.0
      - period -> 4
      - time_remaining -> 360.0
    """
    sanitized_context = _normalize_context(
        margin=margin,
        period=period,
        time_remaining_period_sec=time_remaining_period_sec,
        context=context,
    )

    df = build_ml_matchup_table(
        season=season,
        our_team=our_team,
        opp_team=opp_team,
        w_off=w_off,
        w_def=w_def,
        context=sanitized_context,
    )
    df = apply_context_adjustments(
        df=df,
        margin=sanitized_context["margin"],
        period=sanitized_context["period"],
        time_remaining_period_sec=sanitized_context["time_remaining"],
        context=sanitized_context,
    )

    sort_cols = ["PPP_CONTEXT", "NLP_CONTEXT_ADJ", "PPP_ML_BLEND"]
    sort_cols = [c for c in sort_cols if c in df.columns]
    df = df.sort_values(sort_cols, ascending=False).reset_index(drop=True)
    return df.head(max(1, int(k)))


