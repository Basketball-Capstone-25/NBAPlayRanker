def _fallback_biases_from_context(context: Dict[str, Any]) -> Tuple[Optional[float], Optional[float]]:
    """
    Use parser-provided offense_bias/defense_bias when available.
    Otherwise infer a conservative fallback from the parsed need flags.
    """
    off = _safe_float(context.get("offense_bias"))
    deff = _safe_float(context.get("defense_bias"))
    if off is not None and deff is not None and abs((off + deff) - 1.0) <= 0.25:
        return _clamp(off, 0.0, 1.0), _clamp(deff, 0.0, 1.0)

    needs = set(_as_list_str(context.get("needs")))
    need = _safe_str(context.get("need"))
    if need:
        needs.add(need)

    if "stop" in needs or _truthy(context.get("must_stop")) or _truthy(context.get("no_three")):
        return 0.20, 0.80
    if (
        "need3" in needs
        or "quick2" in needs
        or "two_for_one" in needs
        or "must_score" in needs
        or _truthy(context.get("need3"))
        or _truthy(context.get("quick2"))
        or _truthy(context.get("two_for_one"))
        or _truthy(context.get("must_score"))
    ):
        return 0.75, 0.25
    if "safe" in needs or _truthy(context.get("safe")) or _truthy(context.get("protect_lead")):
        return 0.42, 0.58

    return None, None


def _resolve_effective_weights(
    context: Optional[Dict[str, Any]],
    w_off: float,
    w_def: float,
) -> Tuple[float, float]:
    """
    Let advanced NLP context change how much the ranking trusts our offense
    versus opponent defense. This is a meaningful ranking change, not just text.
    """
    base_w_off = float(w_off)
    ctx = context or {}
    ctx_w_off, _ctx_w_def = _fallback_biases_from_context(ctx)

    if ctx_w_off is None:
        eff_w_off = _clamp(base_w_off, 0.10, 0.90)
        return eff_w_off, float(1.0 - eff_w_off)

    eff_w_off = _clamp(0.35 * base_w_off + 0.65 * ctx_w_off, 0.10, 0.90)
    eff_w_def = float(1.0 - eff_w_off)
    return eff_w_off, eff_w_def


